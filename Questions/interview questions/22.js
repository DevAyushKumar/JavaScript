/* whats the difference between Object.keys, values and entries ?
-> Object.keys() : This will return the array of keys 
-> Object.values() : This will return the array of values
-> Object.entries() : This will return array of [key,values] pairs*/

let data = {
    name : "Ayush",
    lang : "english"
}

Object.keys(data)
Object.values(data)
Object.entries(data)
